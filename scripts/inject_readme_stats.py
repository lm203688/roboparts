# -*- coding: utf-8 -*-
"""
inject_readme_stats.py —— All numbers in the README are computed and injected by this script
================================================================

Background (_MARKET_POSITIONING-20260918.md · P0-2):
    README's top section long hardcoded "688 entities / last updated 2026-08-05",
    while the real value had already become 798 entities. A GitHub visitor's first
    impression was "this project hasn't been maintained for 6 weeks".
    Same discipline as onboarding_block: the single source of truth for numbers = facts(),
    and README keeps no second copy.

[20260921] Injecting only the top two lines is not enough —— a positioning audit found:
    the top had been freshened to 798, but §5 "Data categories" was still an early-August
    snapshot, with all 8 category counts wrong and 10 categories missing:

    actuators   wrote 217  actual 220     sensors            wrote  90  actual  95
    interfaces  wrote  14  actual  44     llms               wrote  23  actual  42
    platforms   wrote  26  actual  41     flexible_actuators wrote 6    actual  22
    robot_ai_models wrote 30 actual 46    data_acquisition   wrote  27  actual  46

**No gate was watching the category counts** (L2 "seven-way consistency" only compares the
total), so it drifted for 7 weeks unnoticed.
"Total correct but subcategories wrong" is more insidious than a wrong total: a reader who
checks the total gets a false sense of "freshness".
Hence this script also brings the §5 category table into the injection surface, and makes the
§11 gate count read live from ci_gate.py (previously written as "8 items", actually 9 sub-gates).

Usage (called by scripts/deploy.mjs / regen_derived.py):
    python scripts/inject_readme_stats.py
Idempotent: marker-wrapped, repeated runs only refresh the content in between.
"""
import os
import re
import subprocess
import sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'scripts'))
import onboarding_block as ob  # noqa: E402

MARK_START = '<!-- RP-STATS:START generated by scripts/inject_readme_stats.py — do not edit by hand -->'
MARK_END = '<!-- RP-STATS:END -->'
CATS_START = '<!-- RP-CATS:START generated by scripts/inject_readme_stats.py — do not edit by hand -->'
CATS_END = '<!-- RP-CATS:END -->'
GATES_START = '<!-- RP-GATES:START generated by scripts/inject_readme_stats.py — do not edit by hand -->'
GATES_END = '<!-- RP-GATES:END -->'

#: Category descriptions (editorial text, owned by this generator; all counts come from facts())
CAT_DESC = {
    'actuators': 'Actuators (motors, harmonic reducers, planetary roller screws, frameless torque motors, drivers, joint modules, dexterous hands, tendon-driven hands, open-source force-controlled joints, SEA, flexible actuators)',
    'chips': 'Chips (AI chips, edge inference accelerators, MCU, FPGA, communication chips)',
    'sensors': 'Sensors (vision cameras, six-axis force/torque sensors, joint torque sensors, tactile sensors, magnetic e-skin, LiDAR, IMU)',
    'protocols': 'Communication protocols (EtherCAT, CANopen, ROS2, MQTT, etc.)',
    'data_acquisition': 'Data acquisition devices (teleoperation, exoskeleton capture, motion capture, data gloves, open-source embodied dataset platforms)',
    'robot_ai_models': 'Robot AI models (VLA models, world models, robot foundation models)',
    'interfaces': 'Interface standards (flanges, buses, connector standard texts)',
    'llms': 'Large models (VLA models, robot foundation models)',
    'platforms': 'Robot platforms (including open-source reproducible complete robots)',
    'grippers': 'Grippers and end effectors',
    'flexible_actuators': 'Flexible actuators (artificial muscles, flexible actuators, bionic spine)',
    'bionic_mechanisms': 'Bionic mechanisms (bionic joints, bionic actuators, bionic sensors)',
    'reducers': 'Reducers (harmonic, planetary, RV)',
    'controllers': 'Controllers',
    'structural': 'Structural parts',
    'cables': 'Cables',
    'connectors': 'Connectors',
    'pcb': 'PCB',
    'power': 'Power supplies',
    'integrated_joints': 'Integrated joint modules',
}


def last_updated():
    """Last updated = date of the most recent commit (falls back to today)."""
    try:
        out = subprocess.run(
            ['git', 'log', '-1', '--date=short', '--format=%cd'],
            cwd=ROOT, capture_output=True, text=True, timeout=30)
        if out.returncode == 0 and out.stdout.strip():
            return out.stdout.strip()
    except Exception:
        pass
    return date.today().isoformat()


def stats_block(f, day):
    return (
        f'- **Data volume / 数据量**: {f["total_entities"]} entities / {f["total_entities"]} 实体'
        f' ({f["component_entities"]} physical parts / {f["specification_entities"]} interface specs / '
        f'{f["software_entities"]} AI model software / {f["organization_entities"]} organizations / '
        f'{f["market_intelligence_entities"]} market intelligence);'
        f'Mechanical interface declaration rate {f["mech_pct"]}% ({f["mech_declared"]}/{f["mech_applicable"]});'
        f'Mechanical interface decidable rate {f["mech_decidable_pct"]}% ({f["mech_decidable"]}/{f["total_entities"]}, standard+flange both non-empty);'
        f'Open-source components {f["oss_total"]}\n'
        f'- **Last updated / 最后更新**: {day}'
    )


def cats_block(f):
    """§5 Data categories: counts from facts(), sorted descending by count.
    Categories missing a description are still listed (not silently dropped)."""
    cc = f['category_counts']
    if sum(cc.values()) != f['total_entities']:
        raise SystemExit('!! category sum (%d) != total (%d); refusing to inject README'
                         % (sum(cc.values()), f['total_entities']))
    missing = sorted(set(cc) - set(CAT_DESC))
    if missing:
        # A new category with no description → let it appear as a bare count
        # rather than be dropped, but must warn loudly.
        print('   ⚠ README category description missing (will list count only): %s' % ' '.join(missing))
    lines = []
    for cat, n in sorted(cc.items(), key=lambda x: (-x[1], x[0])):
        desc = CAT_DESC.get(cat, '')
        lines.append('- **%s**: %d entries%s' % (cat, n, (' — ' + desc) if desc else ''))
    return '\n'.join(lines)


def gate_count():
    """Number of sub-gates registered in ci_gate.py —— read live,
    not hand-written as "8 items" in README.

    Deliberately uses the **actual number of output lines** from `--list`
    rather than regex-parsing the source: a regex version would only count
    the forms it recognizes; if the registry changes form (multi-line lambda /
    line-wrapped tuples) it would silently undercount, and "undercounted a few
    items" would be noticed by no one. Running it once and taking the line count
    is the only wording that cannot lie.
    """
    p = os.path.join(ROOT, 'scripts', 'ci_gate.py')
    out = subprocess.run([sys.executable, p, '--list'],
                         cwd=ROOT, capture_output=True, text=True, timeout=120)
    if out.returncode != 0:
        raise SystemExit('!! ci_gate.py --list exit code %s; refusing to generate README gate count: %s'
                         % (out.returncode, (out.stderr or '')[-300:]))
    names = [x for x in out.stdout.splitlines() if x.strip()]
    if not names:
        raise SystemExit('!! ci_gate.py --list produced empty output; refusing to generate README gate count')
    return len(names)


def _replace_between(text, start, end, body):
    if start in text and end in text:
        head = text[:text.index(start)]
        tail = text[text.index(end) + len(end):]
        return head + body + tail
    return None


def inject(check=False):
    f = ob.facts()
    day = last_updated()
    readme = os.path.join(ROOT, 'README.md')
    with open(readme, encoding='utf-8') as fh:
        text = fh.read()
    original = text
    changed = []

    # ① Top data volume / last updated
    seg = f'{MARK_START}\n{stats_block(f, day)}\n{MARK_END}'
    new = _replace_between(text, MARK_START, MARK_END, seg)
    if new is None:
        new = text.replace('# RoboParts — robot part compatibility judgment layer\n',
                           '# RoboParts — robot part compatibility judgment layer\n\n' + seg + '\n', 1)
    if new != text:
        changed.append('data volume / last updated')
    text = new

    # ② §5 category table
    seg = f'{CATS_START}\n{cats_block(f)}\n{CATS_END}'
    new = _replace_between(text, CATS_START, CATS_END, seg)
    if new is None:
        raise SystemExit('!! README missing RP-CATS marker: if §5 category table is outside the injection surface it will inevitably go stale again')
    if new != text:
        changed.append('category table (%d categories)' % len(f['category_counts']))
    text = new

    # ③ §11 gate count (inline, e.g. `# N gates decidable in-repo`)
    n = gate_count()
    new = _replace_between(text, GATES_START, GATES_END, '%s%d%s' % (GATES_START, n, GATES_END))
    if new is None:
        raise SystemExit('!! README missing RP-GATES marker')
    if new != text:
        changed.append('gate count (%d)' % n)
    text = new

    if check:
        # "Last updated" takes the most recent commit date, unrelated to
        # "whether numbers drifted this run" —— strip it before comparing,
        # otherwise any commit that doesn't regenerate README would false-red
        # (false alarms becoming routine).
        def _strip_date(s):
            return re.sub(r'- \*\*Last updated\*\*:\s*\d{4}-\d{2}-\d{2}',
                          '- **Last updated**: <DATE>', s)
        if _strip_date(text) != _strip_date(original):
            print('❌ README stats block inconsistent with source of truth: %s (run python scripts/inject_readme_stats.py to fix)'
                  % ', '.join(changed))
            return 1
        print('✅ README stats block consistent with source of truth (%d entities / %d gates)' % (f['total_entities'], n))
        return 0

    with open(readme, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print('✅ README injection complete: %d entities / %s; changed %s'
          % (f['total_entities'], day, ', '.join(changed) or 'none'))
    return 0


if __name__ == '__main__':
    sys.exit(inject(check='--check' in sys.argv))
